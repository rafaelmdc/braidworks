"""Generate docs/reference/python-api.md from the public API's docstrings.

The researcher-facing API (``braidworks.get``, ``Session``, ``Result``, ``ReviewItem``,
``Listing``) is documented once, in its docstrings; this renders them as one
reference page so the docs cannot drift from the code.

    uv run python tools/gen_python_api.py           # write the page
    uv run python tools/gen_python_api.py --check   # exit 1 if the page is stale
"""

from __future__ import annotations

import inspect
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "python-api.md"

HEADER = """# Python API reference

<!-- Generated by tools/gen_python_api.py from the docstrings; do not edit by hand.
     Run `make api-docs` after changing a public docstring. -->

The researcher-facing API is `import braidworks as bw`. Start with
[the Python tutorial](../tutorials/first-analysis-in-python.md); task recipes are in
[Work in Python](../how-to/work-in-python.md), and
[What a result means](../explanation/result-meaning.md) explains rows and statuses.
Weaver authors use `braidworks.weaver`; `braidworks.core` is the full engine.
"""

SECTION = re.compile(r"^(Args|Arguments|Returns|Raises|Example|Examples|Attributes)::?\s*$")


def _inline(text: str) -> str:
    """reST inline markup to Markdown: ``x`` and :role:`x` become `x`."""
    text = re.sub(r":[a-z]+:`~?([^`]+)`", r"`\1`", text)
    return text.replace("``", "`")


def render_docstring(doc: str | None) -> str:
    """A Google/reST-style docstring as Markdown (prose, arg lists, code examples)."""
    if not doc:
        return ""
    lines = inspect.cleandoc(doc).splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        match = SECTION.match(line.strip())
        if line.rstrip().endswith("::") and not match:
            # "Some prose::" followed by an indented code block.
            out.append(_inline(line.rstrip()[:-1] + ":"))
            i += 1
            block = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                block.append(lines[i])
                i += 1
            out += ["", "```python", textwrap.dedent("\n".join(block)).strip(), "```", ""]
            continue
        if match:
            name = match.group(1)
            i += 1
            block = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                block.append(lines[i])
                i += 1
            body = textwrap.dedent("\n".join(block)).strip("\n")
            if name.startswith("Example"):
                out += [f"**{name}:**", "", "```python", body, "```", ""]
                continue
            out += [f"**{name}:**", ""]
            items: list[str] = []
            for entry in body.splitlines():
                if not entry.strip():
                    continue
                if entry.startswith(" "):  # continuation of the previous item
                    items[-1] += " " + entry.strip()
                    continue
                key, sep, rest = entry.partition(": ")
                if sep and re.fullmatch(r"\*{0,2}[A-Za-z_][\w.]*", key):
                    items.append(f"- `{key}`: {rest.strip()}")
                else:
                    items.append(f"- {entry.strip()}")
            out += [_inline(item) for item in items] + [""]
            continue
        out.append(_inline(line))
        i += 1
    return "\n".join(out).strip() + "\n"


def _annotation(value) -> str:
    """Annotations are strings under ``from __future__ import annotations``; show them bare."""
    return value if isinstance(value, str) else inspect.formatannotation(value)


def _params(obj, *, drop_self: bool) -> tuple[str, str]:
    sig = inspect.signature(obj)
    parts: list[str] = []
    star_done = False
    for param in sig.parameters.values():
        if drop_self and param.name in ("self", "cls"):
            continue
        if param.kind is param.KEYWORD_ONLY and not star_done:
            parts.append("*")
            star_done = True
        if param.kind is param.VAR_POSITIONAL:
            star_done = True
            text = "*" + param.name
        elif param.kind is param.VAR_KEYWORD:
            text = "**" + param.name
        else:
            text = param.name
        if param.annotation is not param.empty:
            text += f": {_annotation(param.annotation)}"
        if param.default is not param.empty:
            text += f" = {param.default!r}" if param.annotation is not param.empty else f"={param.default!r}"
        parts.append(text)
    ret = "" if sig.return_annotation is sig.empty else f" -> {_annotation(sig.return_annotation)}"
    return ", ".join(parts), ret


def _signature(name: str, obj, *, drop_self: bool = False) -> str:
    try:
        params, ret = _params(obj, drop_self=drop_self)
    except (TypeError, ValueError):
        return name
    prefix = "async def " if inspect.iscoroutinefunction(obj) else "def "
    return f"{prefix}{name}({params}){ret}"


def _constructor(name: str, init) -> str:
    params, _ = _params(init, drop_self=True)
    return f"class {name}({params})"


def _member_entries(cls) -> list[tuple[str, object]]:
    entries = []
    for name, member in cls.__dict__.items():
        if name.startswith("_") and name not in ("__init__",):
            continue
        if name == "__init__":
            continue
        entries.append((name, member))
    return entries


def _render_member(owner: str, name: str, member) -> str:
    if isinstance(member, property):
        doc = render_docstring(member.fget.__doc__ if member.fget else None)
        head = f"#### `{owner}.{name}` (property)"
        return f"{head}\n\n{doc}" if doc else head + "\n"
    func = member.__func__ if isinstance(member, (classmethod, staticmethod)) else member
    if not callable(func):
        return ""
    sig = _signature(name, func, drop_self=True)
    doc = render_docstring(func.__doc__)
    return f"#### `{owner}.{name}`\n\n```python\n{sig}\n```\n\n{doc}"


def build() -> str:
    import braidworks as bw
    from braidworks import Listing, Result, Session
    from braidworks._result import ReviewItem
    from braidworks.core.listing import describe_size

    parts = [HEADER]
    parts.append("## Functions\n")
    for name in ("get", "async_get", "find", "path", "sources"):
        obj = getattr(bw, name)
        parts.append(
            f"### `bw.{name}`\n\n```python\n{_signature(name, obj)}\n```\n\n"
            + render_docstring(obj.__doc__)
        )
    for cls in (Session, Result, ReviewItem, Listing):
        parts.append(f"## `{cls.__name__}`\n")
        init = cls.__dict__.get("__init__")
        if init is not None and cls is not Result and cls is not ReviewItem:
            parts.append(f"```python\n{_constructor(cls.__name__, init)}\n```\n")
        parts.append(render_docstring(cls.__doc__))
        for name, member in _member_entries(cls):
            rendered = _render_member(cls.__name__, name, member)
            if rendered:
                parts.append(rendered)
    parts.append(
        "### `describe_size`\n\n```python\n"
        + _signature("describe_size", describe_size)
        + "\n```\n\n"
        + render_docstring(describe_size.__doc__)
    )
    text = "\n".join(p.rstrip("\n") + "\n" for p in parts)
    return re.sub(r"\n{3,}", "\n\n", text)


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run `make api-docs`", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
