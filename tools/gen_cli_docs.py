"""Generate docs/reference/cli/ — one page per `braidworks` command — from `--help`.

The parser in ``braidworks.core.cli`` is the single source of truth; these pages render
its help so the reference cannot drift from the code (CI runs ``--check``).

    uv run python tools/gen_cli_docs.py           # write the pages
    uv run python tools/gen_cli_docs.py --check   # exit 1 if any page is stale
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

# Deterministic help text: a fixed width and no colour (Python 3.14 colours help).
os.environ["COLUMNS"] = "100"
os.environ["NO_COLOR"] = "1"
os.environ["PYTHON_COLORS"] = "0"

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "cli"
NOTICE = (
    "<!-- Generated by tools/gen_cli_docs.py from `braidworks --help`; do not edit by hand.\n"
    "     Run `make cli-docs` after changing the command line. -->"
)


def _commands(parser: argparse.ArgumentParser) -> list[tuple[str, list[str], str, str]]:
    """``(name, aliases, one-line help, full help)`` per subcommand, in parser order."""
    action = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {choice.dest: choice.help or "" for choice in action._choices_actions}
    seen: dict[int, tuple[str, list[str]]] = {}
    for name, sub in action.choices.items():
        if id(sub) in seen:
            seen[id(sub)][1].append(name)
        else:
            seen[id(sub)] = (name, [])
    parsers = {id(sub): sub for sub in action.choices.values()}
    return [
        (name, aliases, helps.get(name, ""), parsers[key].format_help())
        for key, (name, aliases) in seen.items()
    ]


def _page(name: str, aliases: list[str], summary: str, help_text: str) -> str:
    also = f" Also available as {', '.join(f'`braidworks {a}`' for a in aliases)}." if aliases else ""
    return (
        f"# braidworks {name}\n\n{NOTICE}\n\n"
        f"{summary[:1].upper() + summary[1:]}{also} "
        "For the task this serves, see the [how-to guides](../../how-to/).\n\n"
        f"```text\n{help_text.rstrip()}\n```\n"
    )


def _index(parser: argparse.ArgumentParser, commands) -> str:
    rows = "\n".join(
        f"| [`{name}`]({name}.md)"
        + (f" (alias `{'`, `'.join(aliases)}`)" if aliases else "")
        + f" | {summary} |"
        for name, aliases, summary, _ in commands
    )
    return (
        f"# Command-line reference\n\n{NOTICE}\n\n"
        "Exact options for every `braidworks` command, rendered from its `--help`. "
        "For step-by-step tasks see the [how-to guides](../../how-to/); export fields are "
        "in [result exports](../results.md#command-line-exports).\n\n"
        f"| Command | What it does |\n|---|---|\n{rows}\n\n"
        f"```text\n{parser.format_help().rstrip()}\n```\n"
    )


def pages() -> dict[Path, str]:
    from braidworks.core.cli import build_parser

    parser = build_parser()
    commands = _commands(parser)
    out = {OUT / "index.md": _index(parser, commands)}
    for name, aliases, summary, help_text in commands:
        out[OUT / f"{name}.md"] = _page(name, aliases, summary, help_text)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any page is stale")
    args = parser.parse_args(argv)
    expected = pages()
    existing = set(OUT.glob("*.md")) if OUT.exists() else set()
    stale = sorted(
        str(path.relative_to(ROOT))
        for path, text in expected.items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    )
    extra = sorted(str(path.relative_to(ROOT)) for path in existing - set(expected))
    if args.check:
        if stale or extra:
            for path in stale:
                print(f"stale: {path}")
            for path in extra:
                print(f"no such command: {path}")
            print("Run `make cli-docs` to regenerate the CLI reference.")
            return 1
        print(f"docs/reference/cli is up to date ({len(expected)} pages)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in expected.items():
        path.write_text(text, encoding="utf-8")
    for path in extra:
        path.unlink()
    print(f"wrote {len(expected)} pages to docs/reference/cli")
    return 0


if __name__ == "__main__":
    sys.exit(main())
